ORIENTATION, GPS = 0x0112, 0x8825


def make_image(
    fmt: str = "JPEG",
    size: tuple[int, int] = (2400, 1800),
    mode: str = "RGB",
    orientation: int | None = None,
    gps: bool = False,
) -> bytes:
    image = Image.new(mode, size, (200, 80, 40, 128) if mode == "RGBA" else "orange")
    exif = image.getexif()
    if orientation:
        exif[ORIENTATION] = orientation
    if gps:
        exif[GPS] = {2: (48.0, 51.0, 0.0), 4: (2.0, 21.0, 0.0)}
    buffer = BytesIO()
    image.save(buffer, fmt, **({"exif": exif.tobytes()} if len(exif) else {}))
    return buffer.getvalue()


def open_webp(data: bytes) -> Image.Image:
    image = Image.open(BytesIO(data))
    assert image.format == "WEBP"
    return image


# --- Processing -------------------------------------------------------------------


def test_two_webp_sizes_keeping_the_aspect_ratio() -> None:
    result = process_image(make_image(size=(2400, 1800)))
    assert open_webp(result["large"]).size == (1600, 1200)
    assert open_webp(result["thumb"]).size == (480, 360)


def test_small_photos_are_not_enlarged() -> None:
    result = process_image(make_image(size=(300, 200)))
    assert open_webp(result["large"]).size == (300, 200)


def test_orientation_applied_and_metadata_removed() -> None:
    # Orientation 6: the phone was held upright; the pixels are stored sideways.
    result = process_image(make_image(size=(400, 300), orientation=6, gps=True))
    large = open_webp(result["large"])
    assert large.size == (300, 400)
    assert len(large.getexif()) == 0  # no GPS, no orientation left
    assert "exif" not in large.info


def test_transparency_is_kept() -> None:
    result = process_image(make_image("PNG", (100, 100), mode="RGBA"))
    assert open_webp(result["large"]).mode == "RGBA"


@pytest.mark.parametrize(
    ("data", "code"),
    [
        (b"not an image at all", "invalid_image"),
        (make_image("GIF", (50, 50), mode="P"), "invalid_image"),
        (make_image("PNG", (50, 50))[:60], "invalid_image"),  # truncated
    ],
)
def test_invalid_files_are_refused(data: bytes, code: str) -> None:
    with pytest.raises(ImageError) as err:
        process_image(data)
    assert err.value.code == code


def test_too_large_files_and_dimensions_are_refused(monkeypatch) -> None:
    monkeypatch.setattr(images, "MAX_UPLOAD_BYTES", 1000)
    with pytest.raises(ImageError) as err:
        process_image(b"x" * 1001)
    assert err.value.code == "too_large"

    monkeypatch.setattr(images, "MAX_UPLOAD_BYTES", 10 * 1024 * 1024)
    monkeypatch.setattr(images, "MAX_PIXELS", 100 * 100)
    with pytest.raises(ImageError) as err:
        process_image(make_image(size=(101, 100)))
    assert err.value.code == "too_large"


