async def test_photos_need_authentication_or_a_signed_url(
    hass: HomeAssistant, store, hass_ws_client, hass_client_no_auth
) -> None:
    recipe = await store.async_create({"name": "Tarte"}, None)
    recipe = await store.async_set_image(recipe["id"], make_image(), None)
    anonymous = await hass_client_no_auth()

    path = f"/api/cookbook/images/{recipe['image']}/large.webp"
    assert (await anonymous.get(path)).status == 401
    upload = f"/api/cookbook/recipes/{recipe['id']}/image"
    assert (await anonymous.post(upload, data=upload_form(make_image()))).status == 401

    # The URL given to the frontend (signed for its session) works without the token,
    # as an <img> tag needs; a tampered signature does not.
    ws = await hass_ws_client(hass)
    await ws.send_json_auto_id({"type": "cookbook/get", "recipe_id": recipe["id"]})
    signed = (await ws.receive_json())["result"]["image_url"]
    assert (await anonymous.get(signed)).status == 200
    assert (await anonymous.get(signed[:-4] + "AAAA")).status == 401


