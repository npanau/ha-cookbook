async def test_recipes_carry_signed_photo_urls(
    hass: HomeAssistant, store, hass_ws_client
) -> None:
    recipe = await store.async_create(
        {"name": "Tarte", "ingredients": [{"text": "x", "section": None}]}, None
    )
    await store.async_set_image(recipe["id"], make_image(), None)
    await store.async_create({"name": "Sans photo"}, None)
    ws = await hass_ws_client(hass)

    await ws.send_json_auto_id({"type": "cookbook/list"})
    listed = {r["name"]: r for r in (await ws.receive_json())["result"]["recipes"]}
    assert "authSig=" in listed["Tarte"]["thumbnail_url"]
    assert listed["Sans photo"]["thumbnail_url"] is None

    await ws.send_json_auto_id({"type": "cookbook/get", "recipe_id": recipe["id"]})
    full = (await ws.receive_json())["result"]
    assert "/large.webp?authSig=" in full["image_url"]

    await ws.send_json_auto_id({"type": "cookbook/search", "query": "x"})
    found = (await ws.receive_json())["result"]["recipes"]
    assert found[0]["image_url"] is not None


async def test_import_image(hass: HomeAssistant, store, hass_ws_client) -> None:
    recipe = await store.async_create({"name": "Tarte"}, None)
    ws = await hass_ws_client(hass)

    async def call(**payload):
        await ws.send_json_auto_id({"type": "cookbook/import_image", **payload})
        return await ws.receive_json()

    with patch(
        "custom_components.cookbook.websocket_api.fetch_image",
        return_value=make_image(),
    ):
        response = await call(recipe_id=recipe["id"], url="https://site.fr/p.jpg")
    assert response["success"], response
    assert response["result"]["image"] is not None
    assert "authSig=" in response["result"]["image_url"]

    with patch(
        "custom_components.cookbook.websocket_api.fetch_image",
        side_effect=ScrapeError("blocked_url", "blocked"),
    ):
        response = await call(recipe_id=recipe["id"], url="http://192.168.1.1/p.jpg")
    assert response["error"]["code"] == "blocked_url"

    with patch(
        "custom_components.cookbook.websocket_api.fetch_image", return_value=b"nope"
    ):
        response = await call(recipe_id=recipe["id"], url="https://site.fr/p.jpg")
    assert response["error"]["code"] == "invalid_image"

    response = await call(recipe_id="missing", url="https://site.fr/p.jpg")
    assert response["error"]["code"] == "not_found"
