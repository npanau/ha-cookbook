def upload_form(data: bytes) -> FormData:
    form = FormData()
    form.add_field("file", data, filename="photo.jpg", content_type="image/jpeg")
    return form


def files(store) -> list[str]:
    directory = store.images.directory
    return sorted(p.name for p in directory.iterdir()) if directory.exists() else []


async def test_upload_serve_replace_and_remove(
    hass: HomeAssistant, store, hass_client
) -> None:
    client = await hass_client()
    recipe = await store.async_create({"name": "Tarte"}, None)
    url = f"/api/cookbook/recipes/{recipe['id']}/image"

    response = await client.post(url, data=upload_form(make_image()))
    assert response.status == 200
    body = await response.json()
    first = body["image"]
    assert body["image_url"].startswith(
        f"/api/cookbook/images/{first}/large.webp?authSig="
    )
    assert body["thumbnail_url"].startswith(f"/api/cookbook/images/{first}/thumb.webp?")
    assert body["updated_by"] is not None
    assert files(store) == [f"{first}-large.webp", f"{first}-thumb.webp"]

    served = await client.get(f"/api/cookbook/images/{first}/thumb.webp")
    assert served.status == 200
    assert served.headers["Content-Type"] == "image/webp"
    assert "private" in served.headers["Cache-Control"]
    assert open_webp(await served.read()).size == (480, 360)

    # Replacing deletes the old files.
    response = await client.post(url, data=upload_form(make_image(size=(800, 800))))
    second = (await response.json())["image"]
    assert second != first
    assert files(store) == [f"{second}-large.webp", f"{second}-thumb.webp"]

    # Removing the photo.
    response = await client.delete(url)
    assert response.status == 200
    assert (await response.json())["image"] is None
    assert files(store) == []


