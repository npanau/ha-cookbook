async def test_recipe_deleted_while_its_photo_is_processed(
    hass: HomeAssistant, store
) -> None:
    from custom_components.cookbook.store import RecipeNotFoundError

    recipe = await store.async_create({"name": "Tarte"}, None)
    original_save = store.images.async_save

    async def save_then_delete_recipe(data):
        image_id = await original_save(data)
        await store.async_delete(recipe["id"])
        return image_id

    store.images.async_save = save_then_delete_recipe
    with pytest.raises(RecipeNotFoundError):
        await store.async_set_image(recipe["id"], make_image(), None)
    assert files(store) == []  # the new photo is not left behind


